module Emitters.Rust (emitRust) where

import OntoLogic
import IR
import Data.Char (toLower)
import Text.Read (readMaybe)

-- | Emit idiomatic Rust struct definitions with built-in validation methods
emitRust :: Registry -> String
emitRust reg =
    let modelIR = compileRegistry reg
        classes = irClasses modelIR
        parents = [ (compClassName c, compParentClass c) | c <- classes ]
    in "// Generated by OntoLogic - Rust Model Target\n\n" ++
       concatMap (emitRustStruct parents) classes

emitRustStruct :: [(Name, Maybe Name)] -> CompiledClass -> String
emitRustStruct parents cls =
    let cName = sanitizeIdent (compClassName cls)
        parent = compParentClass cls
        directProps = filter (not . compIsInherited) (compProperties cls)
        structDef =
            "#[derive(Debug, Clone, PartialEq)]\n" ++
            "pub struct " ++ cName ++ " {\n" ++
            maybe "" (\p -> "    pub base: " ++ sanitizeIdent p ++ ",\n") parent ++
            concatMap emitRustField directProps ++
            "}\n\n"
        validateImpl = emitRustValidation parents cls
    in structDef ++ validateImpl

-- | "self." plus one "base." per inheritance level between cls and the class that
--   declares the property. A bound inherited from two levels up needs
--   self.base.base.field, not self.base.field.
fieldAccessor :: [(Name, Maybe Name)] -> Name -> CompiledProperty -> String
fieldAccessor parents cls p =
    "self." ++ concat (replicate (walk cls 0) "base.") ++ toRustFieldName (compPropName p)
  where
    limit = length parents
    walk current n
        | current == compOriginClass p = n
        | n >= limit = n                            -- guard against inheritance cycles
        | otherwise = case lookup current parents of
            Just (Just parent) -> walk parent (n + 1)
            _                  -> n

emitRustField :: CompiledProperty -> String
emitRustField p =
    let fName = toRustFieldName (compPropName p)
        baseType = mapRustType (compPropType p)
        fType = case compCardinality p of
            CardZeroOrOne  -> "Option<" ++ baseType ++ ">"
            CardZeroOrMore -> "Vec<" ++ baseType ++ ">"
            CardOneOrMore  -> "Vec<" ++ baseType ++ ">"
            _              -> baseType
    in "    pub " ++ fName ++ ": " ++ fType ++ ",\n"

emitRustValidation :: [(Name, Maybe Name)] -> CompiledClass -> String
emitRustValidation parents cls =
    let cName = sanitizeIdent (compClassName cls)
        parent = compParentClass cls
        parentCheck = case parent of
            Just _ -> "        if let Err(parent_errs) = self.base.validate() {\n            errors.extend(parent_errs);\n        }\n"
            Nothing -> ""
        allPropsWithConstraints = filter (not . null . compConstraints) (compProperties cls)
        propChecks = concatMap (emitPropValidation parents (compClassName cls)) allPropsWithConstraints
        condChecks = concatMap (emitRustConditionalValidation parents cls) (compConditionalAxioms cls)
        -- `mut` on a vec nothing pushes to is an unused_mut warning in the generated crate.
        mutKeyword = if null parentCheck && null propChecks && null condChecks then "" else "mut "
    in "impl " ++ cName ++ " {\n" ++
       "    pub fn validate(&self) -> Result<(), Vec<String>> {\n" ++
       "        let " ++ mutKeyword ++ "errors = Vec::new();\n" ++
       parentCheck ++
       propChecks ++
       condChecks ++
       "        if errors.is_empty() {\n" ++
       "            Ok(())\n" ++
       "        } else {\n" ++
       "            Err(errors)\n" ++
       "        }\n" ++
       "    }\n" ++
       "}\n\n"

emitPropValidation :: [(Name, Maybe Name)] -> Name -> CompiledProperty -> String
emitPropValidation parents cls p =
    let fAccessor = fieldAccessor parents cls p
        fName = compPropName p
        pType = compPropType p
        constraints = compConstraints p
    in case compCardinality p of
        CardZeroOrOne ->
            let checks = concatMap (emitSingleBound "*val" fName pType) constraints
            in if null constraints then "" else
               "        if let Some(val) = &" ++ fAccessor ++ " {\n" ++
               checks ++
               "        }\n"
        CardZeroOrMore ->
            let checks = concatMap (emitSingleBound "*item" fName pType) constraints
            in if null constraints then "" else
               "        for item in &" ++ fAccessor ++ " {\n" ++
               checks ++
               "        }\n"
        CardOneOrMore ->
            let lenCheck = "        if " ++ fAccessor ++ ".is_empty() {\n            errors.push(\"" ++ fName ++ " must have at least one element\".to_string());\n        }\n"
                checks = concatMap (emitSingleBound "*item" fName pType) constraints
                loopCheck = if null constraints then "" else
                            "        for item in &" ++ fAccessor ++ " {\n" ++
                            checks ++
                            "        }\n"
            in lenCheck ++ loopCheck
        _ ->
            concatMap (emitSingleBound fAccessor fName pType) constraints

emitSingleBound :: String -> String -> PropertyType -> BoundConstraint -> String
emitSingleBound accessor fName pType (BoundConstraint op val) =
    let valStr = if pType `elem` [PTFloat, PTDouble] && not ('.' `elem` valueToString val)
                 then valueToString val ++ ".0"
                 else valueToString val
        (cond, desc) = case op of
            OpGt  -> (accessor ++ " <= " ++ valStr, fName ++ " must be > " ++ valStr)
            OpGte -> (accessor ++ " < " ++ valStr,  fName ++ " must be >= " ++ valStr)
            OpLt  -> (accessor ++ " >= " ++ valStr, fName ++ " must be < " ++ valStr)
            OpLte -> (accessor ++ " > " ++ valStr,  fName ++ " must be <= " ++ valStr)
            OpEq  -> (accessor ++ " != " ++ valStr, fName ++ " must be == " ++ valStr)
            OpNe  -> (accessor ++ " == " ++ valStr, fName ++ " must be != " ++ valStr)
    in "        if " ++ cond ++ " {\n" ++
       "            errors.push(format!(\"" ++ desc ++ ", got {}\", " ++ accessor ++ "));\n" ++
       "        }\n"

mapRustType :: PropertyType -> String
mapRustType PTInteger    = "i64"
mapRustType PTFloat      = "f64"
mapRustType PTDouble     = "f64"
mapRustType PTBoolean    = "bool"
mapRustType PTString     = "String"
mapRustType (PTCustom c) = "Option<Box<" ++ sanitizeIdent c ++ ">>"

toRustFieldName :: String -> String
toRustFieldName name =
    let sanitized = sanitizeIdent name
        lowered = map toLower sanitized
    in case lowered of
        "type"  -> "r#type"
        "match" -> "r#match"
        "fn"    -> "r#fn"
        "mod"   -> "r#mod"
        "struct" -> "r#struct"
        "enum"  -> "r#enum"
        "use"   -> "r#use"
        "ref"   -> "r#ref"
        "move"  -> "r#move"
        "box"   -> "r#box"
        other   -> other

emitRustConditionalValidation :: [(Name, Maybe Name)] -> CompiledClass -> ConditionalConstraint -> String
emitRustConditionalValidation parents cls ax =
    "        if (" ++ emitRustExpr parents cls (condPremise ax) ++ ") && !(" ++ emitRustExpr parents cls (condConclusion ax) ++ ") {\n" ++
    "            errors.push(\"Axiom violation: " ++ escapeRust (condDescription ax) ++ "\".to_string());\n" ++
    "        }\n"

emitRustExpr :: [(Name, Maybe Name)] -> CompiledClass -> FOL -> String
emitRustExpr parents cls (Predicate op args)
    | op `elem` ["eq", "ne", "gt", "gte", "lt", "lte"] =
        case args of
            [Var prop, Constant val] -> emitRustBinary parents cls op prop val
            [Constant val, Var prop] -> emitRustBinary parents cls (invertCompOp op) prop val
            _ -> "true"
    | otherwise =
        case args of
            (Var prop:_) -> "(" ++ resolveRustAccessor parents cls prop ++ " == true)"
            []           -> "(" ++ resolveRustAccessor parents cls op ++ " == true)"
            _            -> "true"
emitRustExpr parents cls (And p1 p2) = "(" ++ emitRustExpr parents cls p1 ++ " && " ++ emitRustExpr parents cls p2 ++ ")"
emitRustExpr parents cls (Or p1 p2)  = "(" ++ emitRustExpr parents cls p1 ++ " || " ++ emitRustExpr parents cls p2 ++ ")"
emitRustExpr parents cls (Not p)     = "!(" ++ emitRustExpr parents cls p ++ ")"
emitRustExpr _ _ _                   = "true"

resolveRustAccessor :: [(Name, Maybe Name)] -> CompiledClass -> Name -> String
resolveRustAccessor parents cls prop =
    case [ p | p <- compProperties cls, compPropName p == prop ] of
        (p:_) -> fieldAccessor parents (compClassName cls) p
        []    -> "self." ++ toRustFieldName prop

resolveRustPropType :: CompiledClass -> Name -> Maybe PropertyType
resolveRustPropType cls prop =
    case [ compPropType p | p <- compProperties cls, compPropName p == prop ] of
        (t:_) -> Just t
        []    -> Nothing

emitRustBinary :: [(Name, Maybe Name)] -> CompiledClass -> String -> Name -> String -> String
emitRustBinary parents cls op prop val =
    let fld = resolveRustAccessor parents cls prop
        mType = resolveRustPropType cls prop
        valExpr = case val of
            "True"  -> "true"
            "False" -> "false"
            v | isNumber v ->
                case mType of
                    Just PTFloat  -> if '.' `elem` v then v else v ++ ".0"
                    Just PTDouble -> if '.' `elem` v then v else v ++ ".0"
                    _             -> v
            v -> "\"" ++ escapeRust v ++ "\".to_string()"
        rustOp = case op of
            "eq"  -> "=="
            "ne"  -> "!="
            "gt"  -> ">"
            "gte" -> ">="
            "lt"  -> "<"
            "lte" -> "<="
            _     -> "=="
    in "(" ++ fld ++ " " ++ rustOp ++ " " ++ valExpr ++ ")"

invertCompOp :: String -> String
invertCompOp "gt"  = "lt"
invertCompOp "gte" = "lte"
invertCompOp "lt"  = "gt"
invertCompOp "lte" = "gte"
invertCompOp op    = op

escapeRust :: String -> String
escapeRust = escapeTargetString

isNumber :: String -> Bool
isNumber s = case (readMaybe s :: Maybe Double) of
    Just _  -> True
    Nothing -> False
