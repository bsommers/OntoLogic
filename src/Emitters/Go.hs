module Emitters.Go (emitGo) where

import OntoLogic
import IR
import Data.Char (toUpper)
import Text.Read (readMaybe)

-- | Emit idiomatic Go struct definitions with validation methods
emitGo :: Registry -> String
emitGo reg =
    let modelIR = compileRegistry reg
        classes = irClasses modelIR
        -- fmt is only referenced by bound checks; an unconditional import makes
        -- constraint-free output fail to compile ("imported and not used").
        usesFmt = any (not . null . compConstraints) (concatMap compProperties classes)
    in "// Code generated by OntoLogic. DO NOT EDIT.\n" ++
       "package models\n\n" ++
       (if usesFmt then "import \"fmt\"\n\n" else "") ++
       concatMap emitGoStruct classes

emitGoStruct :: CompiledClass -> String
emitGoStruct cls =
    let cName = sanitizeIdent (compClassName cls)
        parent = compParentClass cls
        directProps = filter (not . compIsInherited) (compProperties cls)
        structDef =
            "type " ++ cName ++ " struct {\n" ++
            maybe "" (\p -> "    " ++ sanitizeIdent p ++ "\n") parent ++
            concatMap emitGoField directProps ++
            "}\n\n"
        validateImpl = emitGoValidation cls
    in structDef ++ validateImpl

emitGoField :: CompiledProperty -> String
emitGoField p =
    let fName = toPascalCase (compPropName p)
        baseType = mapGoType (compPropType p)
        fType = case compCardinality p of
            CardZeroOrOne  -> if not (null baseType) && head baseType == '*' then baseType else "*" ++ baseType
            CardZeroOrMore -> "[]" ++ baseType
            CardOneOrMore  -> "[]" ++ baseType
            _              -> baseType
        jsonTag = compPropName p
    in "    " ++ fName ++ " " ++ fType ++ " `json:\"" ++ jsonTag ++ ",omitempty\"`\n"

emitGoValidation :: CompiledClass -> String
emitGoValidation cls =
    let cName = sanitizeIdent (compClassName cls)
        parent = compParentClass cls
        recv = "m"
        parentCheck = case parent of
            Just p  -> "    if errs := " ++ recv ++ "." ++ sanitizeIdent p ++ ".Validate(); len(errs) > 0 {\n        allErrors = append(allErrors, errs...)\n    }\n"
            Nothing -> ""
        allPropsWithConstraints = filter (not . null . compConstraints) (compProperties cls)
        propChecks = concatMap (emitGoPropValidation recv) allPropsWithConstraints
        condChecks = concatMap (emitGoConditionalValidation recv) (compConditionalAxioms cls)
    in "func (" ++ recv ++ " *" ++ cName ++ ") Validate() []string {\n" ++
       "    var allErrors []string\n" ++
       parentCheck ++
       propChecks ++
       condChecks ++
       "    return allErrors\n" ++
       "}\n\n"

emitGoPropValidation :: String -> CompiledProperty -> String
emitGoPropValidation recv p =
    let fName = toPascalCase (compPropName p)
        rawName = compPropName p
        pType = compPropType p
        constraints = compConstraints p
        fieldRef = recv ++ "." ++ fName
    in case compCardinality p of
        CardZeroOrOne ->
            let deref = "(*" ++ fieldRef ++ ")"
                checks = concatMap (emitGoSingleBound deref rawName pType) constraints
            in if null constraints then "" else
               "    if " ++ fieldRef ++ " != nil {\n" ++
               checks ++
               "    }\n"
        CardZeroOrMore ->
            let checks = concatMap (emitGoSingleBound "item" rawName pType) constraints
            in if null constraints then "" else
               "    for _, item := range " ++ fieldRef ++ " {\n" ++
               checks ++
               "    }\n"
        CardOneOrMore ->
            let minCheck = "    if len(" ++ fieldRef ++ ") == 0 {\n        allErrors = append(allErrors, \"" ++ rawName ++ " must have at least one element\")\n    }\n"
                checks = concatMap (emitGoSingleBound "item" rawName pType) constraints
                loopCheck = if null constraints then "" else
                            "    for _, item := range " ++ fieldRef ++ " {\n" ++
                            checks ++
                            "    }\n"
            in minCheck ++ loopCheck
        _ ->
            concatMap (emitGoSingleBound fieldRef rawName pType) constraints

emitGoSingleBound :: String -> String -> PropertyType -> BoundConstraint -> String
emitGoSingleBound accessor fName pType (BoundConstraint op val) =
    let valStr = if pType `elem` [PTFloat, PTDouble] && not ('.' `elem` valueToString val)
                 then valueToString val ++ ".0"
                 else valueToString val
        (cond, desc) = case op of
            OpGt  -> (accessor ++ " <= " ++ valStr, fName ++ " must be > " ++ valStr)
            OpGte -> (accessor ++ " < " ++ valStr,  fName ++ " must be >= " ++ valStr)
            OpLt  -> (accessor ++ " >= " ++ valStr, fName ++ " must be < " ++ valStr)
            OpLte -> (accessor ++ " > " ++ valStr,  fName ++ " must be <= " ++ valStr)
            OpEq  -> (accessor ++ " != " ++ valStr, fName ++ " must be == " ++ valStr)
            OpNe  -> (accessor ++ " == " ++ valStr, fName ++ " must be != " ++ valStr)
    in "    if " ++ cond ++ " {\n" ++
       "        allErrors = append(allErrors, fmt.Sprintf(\"" ++ desc ++ ", got %v\", " ++ accessor ++ "))\n" ++
       "    }\n"

mapGoType :: PropertyType -> String
mapGoType PTInteger    = "int64"
mapGoType PTFloat      = "float64"
mapGoType PTDouble     = "float64"
mapGoType PTBoolean    = "bool"
mapGoType PTString     = "string"
mapGoType (PTCustom c) = "*" ++ sanitizeIdent c

-- | Convert arbitrary identifier to PascalCase for exported Go fields
toPascalCase :: String -> String
toPascalCase raw =
    let sanitized = sanitizeIdent raw
        tokens = splitOnUnderscore sanitized
    in concatMap capitalize tokens
  where
    splitOnUnderscore [] = []
    splitOnUnderscore str =
        let (prefix, rest) = break (== '_') str
        in prefix : case rest of
            [] -> []
            (_:r) -> splitOnUnderscore r

    capitalize [] = []
    capitalize (c:cs) = toUpper c : cs

emitGoConditionalValidation :: String -> ConditionalConstraint -> String
emitGoConditionalValidation recv ax =
    "    if (" ++ emitGoExpr recv (condPremise ax) ++ ") && !(" ++ emitGoExpr recv (condConclusion ax) ++ ") {\n" ++
    "        allErrors = append(allErrors, \"Axiom violation: " ++ escapeGo (condDescription ax) ++ "\")\n" ++
    "    }\n"

emitGoExpr :: String -> FOL -> String
emitGoExpr recv (Predicate op args)
    | op `elem` ["eq", "ne", "gt", "gte", "lt", "lte"] =
        case args of
            [Var prop, Constant val] -> emitGoBinary recv op prop val
            [Constant val, Var prop] -> emitGoBinary recv (invertCompOp op) prop val
            _ -> "true"
    | otherwise =
        case args of
            (Var prop:_) -> "(" ++ recv ++ "." ++ toPascalCase prop ++ " == true)"
            []           -> "(" ++ recv ++ "." ++ toPascalCase op ++ " == true)"
            _            -> "true"
emitGoExpr recv (And p1 p2) = "(" ++ emitGoExpr recv p1 ++ " && " ++ emitGoExpr recv p2 ++ ")"
emitGoExpr recv (Or p1 p2)  = "(" ++ emitGoExpr recv p1 ++ " || " ++ emitGoExpr recv p2 ++ ")"
emitGoExpr recv (Not p)     = "!(" ++ emitGoExpr recv p ++ ")"
emitGoExpr _ _              = "true"

emitGoBinary :: String -> String -> Name -> String -> String
emitGoBinary recv op prop val =
    let fld = recv ++ "." ++ toPascalCase prop
        valExpr = case val of
            "True"  -> "true"
            "False" -> "false"
            v | isNumber v -> v
            v -> "\"" ++ escapeGo v ++ "\""
        goOp = case op of
            "eq"  -> "=="
            "ne"  -> "!="
            "gt"  -> ">"
            "gte" -> ">="
            "lt"  -> "<"
            "lte" -> "<="
            _     -> "=="
    in "(" ++ fld ++ " " ++ goOp ++ " " ++ valExpr ++ ")"

invertCompOp :: String -> String
invertCompOp "gt"  = "lt"
invertCompOp "gte" = "lte"
invertCompOp "lt"  = "gt"
invertCompOp "lte" = "gte"
invertCompOp op    = op

escapeGo :: String -> String
escapeGo = escapeTargetString

isNumber :: String -> Bool
isNumber s = case (readMaybe s :: Maybe Double) of
    Just _  -> True
    Nothing -> False
