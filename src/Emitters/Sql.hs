module Emitters.Sql
    ( emitSql
    , sqlIdent
    , escapeSqlString
    ) where

import OntoLogic
import IR
import Data.Char (toLower)
import Data.List (intercalate)
import Text.Read (readMaybe)

import qualified Data.Set as Set

-- | Emit PostgreSQL / ANSI SQL DDL schema from ModelIR
emitSql :: Registry -> String
emitSql reg =
    let modelIR = compileRegistry reg
        classes = irClasses modelIR
        relationsList = irRelations modelIR
        classTables = map emitSqlClass classes
        relTables = map emitSqlRelation relationsList
        allStatements = classTables ++ relTables
    in "-- Code generated by OntoLogic. DO NOT EDIT.\n\n" ++
       intercalate "\n\n" (filter (not . null) allStatements) ++ "\n"

emitSqlClass :: CompiledClass -> String
emitSqlClass cls =
    let tName = sqlIdent (compClassName cls)
        parent = compParentClass cls
        idCol = case parent of
            Just p  -> "    \"id\" TEXT PRIMARY KEY REFERENCES " ++ sqlIdent p ++ "(\"id\") ON DELETE CASCADE"
            Nothing -> "    \"id\" TEXT PRIMARY KEY"
        directProps = filter (not . compIsInherited) (compProperties cls)
        directCols = Set.fromList ("id" : map compPropName directProps)
        propCols = map emitSqlColumn directProps
        propChecks = concatMap (emitSqlPropCheck (compClassName cls)) (filter (not . null . compConstraints) directProps)
        condChecks = concatMap (emitSqlCondCheck directCols (compClassName cls)) (zip [1..] (compConditionalAxioms cls))
        tableElements = [idCol] ++ propCols ++ propChecks ++ condChecks
    in "CREATE TABLE IF NOT EXISTS " ++ tName ++ " (\n" ++
       intercalate ",\n" tableElements ++
       "\n);"

emitSqlColumn :: CompiledProperty -> String
emitSqlColumn p =
    let colName = sqlIdent (compPropName p)
        colType = mapSqlType (compPropType p) (compCardinality p)
        defClause = case compDefaultValue p of
            Just val -> " DEFAULT " ++ formatDefault (compPropType p) val
            Nothing  -> ""
        notNullClause = case compCardinality p of
            CardZeroOrOne  -> ""
            CardZeroOrMore -> ""
            _              -> " NOT NULL"
    in "    " ++ colName ++ " " ++ colType ++ defClause ++ notNullClause

mapSqlType :: PropertyType -> Cardinality -> String
mapSqlType pType card =
    let isArray = card `elem` [CardZeroOrMore, CardOneOrMore]
        baseType = case pType of
            PTInteger    -> "INTEGER"
            PTFloat      -> "DOUBLE PRECISION"
            PTDouble     -> "DOUBLE PRECISION"
            PTBoolean    -> "BOOLEAN"
            PTString     -> "TEXT"
            PTCustom c   -> "TEXT REFERENCES " ++ sqlIdent c ++ "(\"id\") ON DELETE SET NULL"
    in if isArray
       then case pType of
           PTCustom _ -> "TEXT[]"
           _          -> baseType ++ "[]"
       else baseType

formatDefault :: PropertyType -> String -> String
formatDefault PTBoolean val =
    case map toLower val of
        "true"  -> "TRUE"
        "false" -> "FALSE"
        _       -> if val == "1" then "TRUE" else "FALSE"
formatDefault PTInteger val = val
formatDefault PTFloat val   = val
formatDefault PTDouble val  = val
formatDefault _ val         = "'" ++ escapeSqlString val ++ "'"

emitSqlPropCheck :: Name -> CompiledProperty -> [String]
emitSqlPropCheck cName p =
    case compConstraints p of
        [] -> []
        cs ->
            let fld = sqlIdent (compPropName p)
                chkName = sqlIdent ("chk_" ++ sanitizeIdent cName ++ "_" ++ sanitizeIdent (compPropName p))
                conds = map (emitBoundCheck fld) cs
                checkExpr = intercalate " AND " conds
            in ["    CONSTRAINT " ++ chkName ++ " CHECK (" ++ checkExpr ++ ")"]

emitBoundCheck :: String -> BoundConstraint -> String
emitBoundCheck fld (BoundConstraint op val) =
    let opStr = case op of
            OpEq  -> "= "
            OpNe  -> "<> "
            OpGt  -> "> "
            OpGte -> ">= "
            OpLt  -> "< "
            OpLte -> "<= "
        valStr = formatVal val
    in fld ++ " " ++ opStr ++ valStr
  where
    formatVal (VInt n)    = show n
    formatVal (VDouble d) = show d
    formatVal (VBool b)   = if b then "TRUE" else "FALSE"
    formatVal (VString s) = "'" ++ escapeSqlString s ++ "'"

emitSqlCondCheck :: Set.Set Name -> Name -> (Int, ConditionalConstraint) -> [String]
emitSqlCondCheck directCols cName (idx, ax) =
    let chkName = sqlIdent ("chk_" ++ sanitizeIdent cName ++ "_cond" ++ show idx)
        refProps = getReferencedProps (condPremise ax) ++ getReferencedProps (condConclusion ax)
    in if all (`Set.member` directCols) refProps
       then case (emitSqlExpr (condPremise ax), emitSqlExpr (condConclusion ax)) of
           (Just p, Just c) -> ["    CONSTRAINT " ++ chkName ++ " CHECK (NOT (" ++ p ++ ") OR (" ++ c ++ "))"]
           _                -> []
       else []

getReferencedProps :: FOL -> [Name]
getReferencedProps (Predicate op args)
    | op `elem` ["eq", "ne", "gt", "gte", "lt", "lte"] =
        [prop | Var prop <- args] ++ [prop | Apply prop _ <- args]
    | otherwise =
        [prop | Var prop <- args] ++ [prop | Apply prop _ <- args] ++ [op | null args]
getReferencedProps (Eq t1 t2) =
    let fromTerm (Var p)     = [p]
        fromTerm (Apply p _) = [p]
        fromTerm _           = []
    in fromTerm t1 ++ fromTerm t2
getReferencedProps (And p1 p2) = getReferencedProps p1 ++ getReferencedProps p2
getReferencedProps (Or p1 p2)  = getReferencedProps p1 ++ getReferencedProps p2
getReferencedProps (Not p)     = getReferencedProps p
getReferencedProps _           = []

emitSqlExpr :: FOL -> Maybe String
emitSqlExpr (Predicate op args)
    | op `elem` ["eq", "ne", "gt", "gte", "lt", "lte"] =
        case args of
            [Var prop, Constant val]     -> Just (emitBinarySql op prop val)
            [Constant val, Var prop]     -> Just (emitBinarySql (invertCompOp op) prop val)
            [Apply prop _, Constant val] -> Just (emitBinarySql op prop val)
            [Constant val, Apply prop _] -> Just (emitBinarySql (invertCompOp op) prop val)
            _ -> Nothing
    | otherwise =
        case args of
            (Var prop:_)     -> Just (sqlIdent prop ++ " = TRUE")
            (Apply prop _:_) -> Just (sqlIdent prop ++ " = TRUE")
            []               -> Just (sqlIdent op ++ " = TRUE")
            _                -> Nothing
emitSqlExpr (Eq t1 t2) =
    case (t1, t2) of
        (Var prop, Constant val)     -> Just (emitBinarySql "eq" prop val)
        (Constant val, Var prop)     -> Just (emitBinarySql "eq" prop val)
        (Apply prop _, Constant val) -> Just (emitBinarySql "eq" prop val)
        (Constant val, Apply prop _) -> Just (emitBinarySql "eq" prop val)
        (Var p1, Var p2)             -> Just (sqlIdent p1 ++ " = " ++ sqlIdent p2)
        _                            -> Nothing
emitSqlExpr (And p1 p2) = do
    e1 <- emitSqlExpr p1
    e2 <- emitSqlExpr p2
    Just ("(" ++ e1 ++ " AND " ++ e2 ++ ")")
emitSqlExpr (Or p1 p2) = do
    e1 <- emitSqlExpr p1
    e2 <- emitSqlExpr p2
    Just ("(" ++ e1 ++ " OR " ++ e2 ++ ")")
emitSqlExpr (Not p) = do
    e <- emitSqlExpr p
    Just ("NOT (" ++ e ++ ")")
emitSqlExpr Top = Just "TRUE"
emitSqlExpr Bottom = Just "FALSE"
emitSqlExpr _ = Nothing

emitBinarySql :: String -> Name -> String -> String
emitBinarySql op prop val =
    let fld = sqlIdent prop
        sqlOp = case op of
            "eq"  -> "= "
            "ne"  -> "<> "
            "gt"  -> "> "
            "gte" -> ">= "
            "lt"  -> "< "
            "lte" -> "<= "
            _     -> "= "
        sqlVal = case map toLower val of
            "true"  -> "TRUE"
            "false" -> "FALSE"
            _       -> if isNumber val then val else "'" ++ escapeSqlString val ++ "'"
    in fld ++ " " ++ sqlOp ++ sqlVal

emitSqlRelation :: CompiledRelation -> String
emitSqlRelation rel =
    let tName = sqlIdent ("rel_" ++ sanitizeIdent (compRelName rel))
        srcTable = sqlIdent (compRelDomain rel)
        tgtTable = sqlIdent (compRelRange rel)
        srcCol = "    \"source_id\" TEXT NOT NULL REFERENCES " ++ srcTable ++ "(\"id\") ON DELETE CASCADE"
        tgtCol = "    \"target_id\" TEXT NOT NULL REFERENCES " ++ tgtTable ++ "(\"id\") ON DELETE CASCADE"
        pk = "    PRIMARY KEY (\"source_id\", \"target_id\")"
    in "CREATE TABLE IF NOT EXISTS " ++ tName ++ " (\n" ++
       srcCol ++ ",\n" ++
       tgtCol ++ ",\n" ++
       pk ++
       "\n);"

sqlIdent :: String -> String
sqlIdent s = "\"" ++ concatMap (\c -> if c == '"' then "\"\"" else [c]) (sanitizeIdent s) ++ "\""

escapeSqlString :: String -> String
escapeSqlString = concatMap (\c -> if c == '\'' then "''" else [c])

isNumber :: String -> Bool
isNumber s = case (readMaybe s :: Maybe Double) of
    Just _  -> True
    Nothing -> False

invertCompOp :: String -> String
invertCompOp "gt"  = "lt"
invertCompOp "gte" = "lte"
invertCompOp "lt"  = "gt"
invertCompOp "lte" = "gte"
invertCompOp op    = op
