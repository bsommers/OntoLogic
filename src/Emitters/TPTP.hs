module Emitters.TPTP
    ( emitTPTP
    , emitTPTPSubsumption
    , emitTPTPCoherence
    , folToTPTP
    , termToTPTP
    , tptpVar
    , tptpConst
    ) where

import Data.Char (toLower)
import Data.List (intercalate)
import qualified Data.Map as Map
import Data.Containers.ListUtils (nubOrd)
import OntoLogic
import FOLTheory (Env(..), makeEnv)

-- | Emit complete TPTP First-Order Form (FOF) problem specification
emitTPTP :: Registry -> String
emitTPTP reg =
    let env = makeEnv reg
        subclasses = concatMap emitSubclass (nubOrd (concepts reg))
        relSigs = concatMap emitRelSig (relations reg)
        propSigs = concatMap emitPropSig (properties reg)
        indSigs = concatMap emitIndividual (individuals reg)
        axEntries = [ "fof(ax_" ++ show idx ++ ", axiom, " ++ s ++ ").\n"
                    | (idx, ax) <- zip ([1..] :: [Int]) (axioms reg)
                    , Right s <- [folToTPTP env [] ax]
                    ]
        -- FOF has no arithmetic; state which numeric bounds exclude each other.
        arithAxioms = concat
            [ "fof(arith_" ++ show i ++ ", axiom, (! [T] : ~(cmp_" ++ op1 ++ "(T, " ++ tptpConst a ++ ") & cmp_"
                ++ op2 ++ "(T, " ++ tptpConst b ++ ")))).\n"
            | (i, ((op1, a), (op2, b))) <- zip ([1..] :: [Int]) (disjointBoundPairs (axioms reg))
            ]
        header = "% TPTP First-Order Form (FOF) generated by OntoLogic\n\n"
        sections = filter (not . null)
            [ subclasses
            , relSigs
            , propSigs
            , indSigs
            , concat axEntries
            , arithAxioms
            ]
    in header ++ intercalate "\n" sections

-- | Emit TPTP with a conjecture to prove concept subsumption (Child <= Parent)
emitTPTPSubsumption :: Registry -> String -> String -> String
emitTPTPSubsumption reg child parent =
    emitTPTP reg ++
    "\n% Subsumption Conjecture: " ++ child ++ " <= " ++ parent ++ "\n" ++
    "fof(conjecture_subsumption, conjecture, (! [X] : (is_" ++ sanitizeIdent child ++ "(X) => is_" ++ sanitizeIdent parent ++ "(X)))).\n"

-- | Emit TPTP to test concept coherence (satisfiability / non-emptiness)
emitTPTPCoherence :: Registry -> String -> String
emitTPTPCoherence reg c =
    emitTPTP reg ++
    "\n% Concept Coherence Check: exists an instance of " ++ c ++ "\n" ++
    "fof(assert_nonempty_" ++ sanitizeIdent c ++ ", axiom, (? [X] : is_" ++ sanitizeIdent c ++ "(X))).\n"

emitIndividual :: (Name, Maybe Name) -> String
emitIndividual (ind, Just c) =
    "fof(ind_" ++ sanitizeIdent ind ++ "_type, axiom, is_" ++ sanitizeIdent c ++ "(" ++ tptpConst ind ++ ")).\n"
emitIndividual _ = ""

emitSubclass :: (Name, Maybe Name) -> String
emitSubclass (c, Just p) =
    "fof(subclass_" ++ sanitizeIdent c ++ "_" ++ sanitizeIdent p ++ ", axiom, (! [X] : (is_" ++ sanitizeIdent c ++ "(X) => is_" ++ sanitizeIdent p ++ "(X)))).\n"
emitSubclass _ = ""

emitRelSig :: Relation -> String
emitRelSig r =
    let rName = sanitizeIdent (relName r)
        dName = sanitizeIdent (relDomain r)
        rngName = sanitizeIdent (relRange r)
    in "fof(rel_domain_" ++ rName ++ ", axiom, (! [X, Y] : (rel_" ++ rName ++ "(X, Y) => is_" ++ dName ++ "(X)))).\n" ++
       "fof(rel_range_" ++ rName ++ ", axiom, (! [X, Y] : (rel_" ++ rName ++ "(X, Y) => is_" ++ rngName ++ "(Y)))).\n"

emitPropSig :: Property -> String
emitPropSig p = case rangeType p of
    PTCustom r ->
        let pName = sanitizeIdent (propName p)
            dName = sanitizeIdent (domain p)
            rngName = sanitizeIdent r
        in "fof(prop_domain_" ++ pName ++ ", axiom, (! [X, Y] : (prop_" ++ pName ++ "(X, Y) => is_" ++ dName ++ "(X)))).\n" ++
           "fof(prop_range_" ++ pName ++ ", axiom, (! [X, Y] : (prop_" ++ pName ++ "(X, Y) => is_" ++ rngName ++ "(Y)))).\n"
    _ -> ""

-- | Translate OntoLogic FOL into TPTP First-Order Form (FOF)
folToTPTP :: Env -> [Name] -> FOL -> Either String String
folToTPTP env bound f = case f of
    ForAll v b -> do
        b' <- folToTPTP env (v : bound) b
        Right ("(! [" ++ tptpVar v ++ "] : " ++ b' ++ ")")
    Exists v b -> do
        b' <- folToTPTP env (v : bound) b
        Right ("(? [" ++ tptpVar v ++ "] : " ++ b' ++ ")")
    TypedForAll v sort b
        | sort `elem` envConcepts env -> do
            b' <- folToTPTP env (v : bound) b
            Right ("(! [" ++ tptpVar v ++ "] : (is_" ++ sanitizeIdent sort ++ "(" ++ tptpVar v ++ ") => " ++ b' ++ "))")
        | otherwise -> do
            b' <- folToTPTP env (v : bound) b
            Right ("(! [" ++ tptpVar v ++ "] : " ++ b' ++ ")")
    TypedExists v sort b
        | sort `elem` envConcepts env -> do
            b' <- folToTPTP env (v : bound) b
            Right ("(? [" ++ tptpVar v ++ "] : (is_" ++ sanitizeIdent sort ++ "(" ++ tptpVar v ++ ") & " ++ b' ++ "))")
        | otherwise -> do
            b' <- folToTPTP env (v : bound) b
            Right ("(? [" ++ tptpVar v ++ "] : " ++ b' ++ ")")
    Top    -> Right "$true"
    Bottom -> Right "$false"
    Eq (Var prop) term
        | Map.member prop (envProps env), prop `notElem` bound -> case bound of
            (subject : _) -> do
                t' <- termToTPTP env bound term
                Right ("(prop_" ++ sanitizeIdent prop ++ "(" ++ tptpVar subject ++ ") = " ++ t' ++ ")")
            [] -> do
                t' <- termToTPTP env bound term
                Right ("(prop_" ++ sanitizeIdent prop ++ " = " ++ t' ++ ")")
    Eq term (Var prop)
        | Map.member prop (envProps env), prop `notElem` bound -> case bound of
            (subject : _) -> do
                t' <- termToTPTP env bound term
                Right ("(prop_" ++ sanitizeIdent prop ++ "(" ++ tptpVar subject ++ ") = " ++ t' ++ ")")
            [] -> do
                t' <- termToTPTP env bound term
                Right ("(prop_" ++ sanitizeIdent prop ++ " = " ++ t' ++ ")")
    Eq t1 t2 -> do
        s1 <- termToTPTP env bound t1
        s2 <- termToTPTP env bound t2
        Right ("(" ++ s1 ++ " = " ++ s2 ++ ")")
    And a b     -> bin "&" a b
    Or a b      -> bin "|" a b
    Implies a b -> bin "=>" a b
    Iff a b     -> bin "<=>" a b
    Not a       -> do
        s <- folToTPTP env bound a
        Right ("(~" ++ s ++ ")")
    Predicate name args -> predicate name args
  where
    bin op a b = do
        sa <- folToTPTP env bound a
        sb <- folToTPTP env bound b
        Right ("(" ++ sa ++ " " ++ op ++ " " ++ sb ++ ")")

    predicate "eq" [t1, t2] = do
        s1 <- termToTPTP env bound t1
        s2 <- termToTPTP env bound t2
        Right ("(" ++ s1 ++ " = " ++ s2 ++ ")")
    predicate "=" [t1, t2] = predicate "eq" [t1, t2]
    predicate "ne" [t1, t2] = do
        s1 <- termToTPTP env bound t1
        s2 <- termToTPTP env bound t2
        Right ("(" ++ s1 ++ " != " ++ s2 ++ ")")
    predicate "!=" [t1, t2] = predicate "ne" [t1, t2]

    predicate op [Var p, Constant c]
        | op `elem` ["gt", "gte", "lt", "lte"] = case bound of
            (subject : _) -> Right ("cmp_" ++ op ++ "(prop_" ++ sanitizeIdent p ++ "(" ++ tptpVar subject ++ "), " ++ tptpConst c ++ ")")
            []            -> Right ("cmp_" ++ op ++ "(prop_" ++ sanitizeIdent p ++ ", " ++ tptpConst c ++ ")")
    predicate op [Constant c, Var p]
        | op `elem` ["gt", "gte", "lt", "lte"] =
            predicate (invertCompOp op) [Var p, Constant c]

    predicate name []
        | Just PTBoolean <- Map.lookup name (envProps env) = case bound of
            (subject : _) -> Right ("prop_" ++ sanitizeIdent name ++ "(" ++ tptpVar subject ++ ")")
            []            -> Right ("prop_" ++ sanitizeIdent name)
        | otherwise = Right ("pred_" ++ sanitizeIdent name)

    predicate name [Var v]
        | name `elem` envConcepts env = Right ("is_" ++ sanitizeIdent name ++ "(" ++ tptpVar v ++ ")")
        | Just PTBoolean <- Map.lookup name (envProps env) = Right ("prop_" ++ sanitizeIdent name ++ "(" ++ tptpVar v ++ ")")

    predicate name args
        | name `elem` envConcepts env = do
            argStrs <- mapM (termToTPTP env bound) args
            Right ("is_" ++ sanitizeIdent name ++ "(" ++ intercalate ", " argStrs ++ ")")
        | name `elem` envRelations env = do
            argStrs <- mapM (termToTPTP env bound) args
            Right ("rel_" ++ sanitizeIdent name ++ "(" ++ intercalate ", " argStrs ++ ")")
        | Map.member name (envProps env) = do
            argStrs <- mapM (termToTPTP env bound) args
            Right ("prop_" ++ sanitizeIdent name ++ "(" ++ intercalate ", " argStrs ++ ")")
        | otherwise = do
            argStrs <- mapM (termToTPTP env bound) args
            Right ("up_" ++ sanitizeIdent name ++ "(" ++ intercalate ", " argStrs ++ ")")

-- | Translate an OntoLogic term to a TPTP term
termToTPTP :: Env -> [Name] -> Term -> Either String String
termToTPTP _ bound (Var v)
    | v `elem` bound = Right (tptpVar v)
    | otherwise      = Right (tptpConst v)
termToTPTP _ _ (Constant c) = Right (tptpConst c)
termToTPTP env bound (Apply fn args) = do
    argStrs <- mapM (termToTPTP env bound) args
    let prefix = if Map.member fn (envProps env) then "prop_" else "fn_"
    Right (prefix ++ sanitizeIdent fn ++ "(" ++ intercalate ", " argStrs ++ ")")

tptpVar :: Name -> String
tptpVar v = "V_" ++ sanitizeIdent v

tptpConst :: String -> String
tptpConst c = case map toLower c of
    "true"  -> "c_true"
    "false" -> "c_false"
    _ -> case parseValue c of
        VInt i    -> if i < 0 then "c_neg_" ++ show (abs i) else "c_" ++ show i
        VDouble d -> "c_" ++ map (\ch -> if ch == '.' then '_' else if ch == '-' then 'm' else ch) (show d)
        VBool b   -> if b then "c_true" else "c_false"
        VString s -> "c_" ++ sanitizeIdent s

invertCompOp :: String -> String
invertCompOp "gt"  = "lt"
invertCompOp "gte" = "lte"
invertCompOp "lt"  = "gt"
invertCompOp "lte" = "gte"
invertCompOp op    = op
