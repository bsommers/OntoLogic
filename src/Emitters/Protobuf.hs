module Emitters.Protobuf (emitProtobuf) where

import OntoLogic
import IR
import Data.Char (toLower)

-- | Emit Protocol Buffers v3 (proto3) schema definitions
emitProtobuf :: Registry -> String
emitProtobuf reg =
    let modelIR = compileRegistry reg
        classes = irClasses modelIR
        pkg = case namespaces reg of
            (NamespaceDecl ns _:_) -> map (\c -> if c `elem` (":/-." :: String) then '_' else toLower c) ns
            []                     -> "ontologic"
    in "// Code generated by OntoLogic. DO NOT EDIT.\n" ++
       "syntax = \"proto3\";\n\n" ++
       "package " ++ pkg ++ ";\n\n" ++
       concatMap emitProtoMessage classes

emitProtoMessage :: CompiledClass -> String
emitProtoMessage cls =
    let cName = sanitizeIdent (compClassName cls)
        parentComment = case compParentClass cls of
            Just p  -> "    // Inherits from " ++ p ++ "\n"
            Nothing -> ""
        directProps = filter (not . compIsInherited) (compProperties cls)
        fields = zipWith emitProtoField ([1..] :: [Int]) directProps
        body = if null directProps && null parentComment
               then "    // Empty concept message\n"
               else parentComment ++ concat fields
    in "message " ++ cName ++ " {\n" ++ body ++ "}\n\n"

emitProtoField :: Int -> CompiledProperty -> String
emitProtoField tag p =
    let fName = sanitizeIdent (compPropName p)
        baseType = mapProtoType (compPropType p)
        defNote = case compDefaultValue p of
            Just d  -> ["default: " ++ d]
            Nothing -> []
        (modifier, notes) = case compCardinality p of
            CardZeroOrOne  -> ("optional ", defNote)
            CardZeroOrMore -> ("repeated ", defNote)
            CardOneOrMore  -> ("repeated ", ["min_count: 1"] ++ defNote)
            _              -> ("", defNote)
        comment = case notes of
            [] -> ""
            _  -> " // " ++ unwords notes
    in "    " ++ modifier ++ baseType ++ " " ++ fName ++ " = " ++ show tag ++ ";" ++ comment ++ "\n"

mapProtoType :: PropertyType -> String
mapProtoType PTInteger    = "int64"
mapProtoType PTFloat      = "float"
mapProtoType PTDouble     = "double"
mapProtoType PTString     = "string"
mapProtoType PTBoolean    = "bool"
mapProtoType (PTCustom c) = sanitizeIdent c
