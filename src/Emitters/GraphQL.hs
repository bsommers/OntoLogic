{-# LANGUAGE ScopedTypeVariables #-}
module Emitters.GraphQL (emitGraphQL) where

import OntoLogic
import IR
import Data.Char (toLower)

-- | Emit GraphQL SDL schema from ModelIR
emitGraphQL :: Registry -> String
emitGraphQL reg =
    let modelIR = compileRegistry reg
        classes = irClasses modelIR
        typeDefs = concatMap (emitGraphQLType classes) classes
        rootQuery =
            "type Query {\n" ++
            concat [ "  " ++ field ++ ": [" ++ sanitizeIdent (compClassName cls) ++ "!]!\n"
                   | (cls, field) <- zip classes (queryFieldNames classes) ] ++
            "}\n"
    in "# Code generated by OntoLogic. DO NOT EDIT.\n\n" ++ typeDefs ++ rootQuery

-- | Query field per class, made unique: lowercase first letter, plural, then _2, _3
--   on collision. Concepts differing only in namespace or case would otherwise
--   collapse to one field name and invalidate the whole schema.
queryFieldNames :: [CompiledClass] -> [String]
queryFieldNames = go []
  where
    go _ [] = []
    go seen (c:cs) =
        let base = plural (sanitizeIdent (compClassName c))
            name = disambiguate seen base 1
        in name : go (name : seen) cs
    plural (x:xs) = toLower x : xs ++ "s"
    plural []     = "items"
    disambiguate :: [String] -> String -> Int -> String
    disambiguate seen base n
        | candidate `elem` seen = disambiguate seen base (n + 1)
        | otherwise = candidate
      where candidate = if n == 1 then base else base ++ "_" ++ show n

-- | A class's own properties plus its ancestors'. GraphQL has no schema-level
--   inheritance, so a subclass type must repeat the parent's fields. The chain
--   lists the class before its ancestors and nubByName keeps the first
--   occurrence, so a subclass definition wins.
inheritedProperties :: [CompiledClass] -> CompiledClass -> [CompiledProperty]
inheritedProperties classes cls =
    let parents = [ (compClassName c, compParentClass c) | c <- classes ]
        chain = compClassName cls : getAncestors (compClassName cls) parents
        props = [ p | n <- chain, c <- classes, compClassName c == n, p <- compProperties c ]
    in nubByName props
  where
    nubByName = foldr (\p acc -> if any ((== compPropName p) . compPropName) acc then acc else p : acc) []

emitGraphQLType :: [CompiledClass] -> CompiledClass -> String
emitGraphQLType classes cls =
    let props = inheritedProperties classes cls
        fieldLines = if null props then "  _empty: Boolean\n" else concatMap emitGraphQLField props
    in "type " ++ sanitizeIdent (compClassName cls) ++ " {\n" ++ fieldLines ++ "}\n\n"

emitGraphQLField :: CompiledProperty -> String
emitGraphQLField p =
    let fName = sanitizeIdent (compPropName p)
        gType = formatGraphQLFieldType (compPropType p) (compCardinality p)
    in "  " ++ fName ++ ": " ++ gType ++ "\n"

mapGraphQLBaseType :: PropertyType -> String
mapGraphQLBaseType PTInteger    = "Int"
mapGraphQLBaseType PTFloat      = "Float"
mapGraphQLBaseType PTDouble     = "Float"
mapGraphQLBaseType PTBoolean    = "Boolean"
mapGraphQLBaseType PTString     = "String"
mapGraphQLBaseType (PTCustom c) = sanitizeIdent c

formatGraphQLFieldType :: PropertyType -> Cardinality -> String
formatGraphQLFieldType pt card =
    let base = mapGraphQLBaseType pt
    in case card of
        CardZeroOrOne  -> base
        CardZeroOrMore -> "[" ++ base ++ "!]"
        CardOneOrMore  -> "[" ++ base ++ "!]!"
        CardExactlyOne -> base ++ "!"
        CardDefault    -> case pt of
            PTCustom _ -> base
            _          -> base ++ "!"
