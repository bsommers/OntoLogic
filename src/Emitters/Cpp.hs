module Emitters.Cpp (emitCpp) where

import OntoLogic
import IR

-- | Emit modern C++20 header definitions with validation
emitCpp :: Registry -> String
emitCpp reg =
    let modelIR = compileRegistry reg
        classes = irClasses modelIR
        fwdDecls = concatMap (\c -> "struct " ++ sanitizeIdent (compClassName c) ++ ";\n") classes
    in "// Code generated by OntoLogic. DO NOT EDIT.\n" ++
       "#pragma once\n\n" ++
       "#include <cstdint>\n" ++
       "#include <string>\n" ++
       "#include <vector>\n" ++
       "#include <optional>\n" ++
       "#include <memory>\n" ++
       "#include <stdexcept>\n\n" ++
       "namespace ontologic {\n\n" ++
       "// Forward declarations\n" ++
       fwdDecls ++ "\n" ++
       concatMap emitCppStruct classes ++
       "} // namespace ontologic\n"

emitCppStruct :: CompiledClass -> String
emitCppStruct cls =
    let cName = sanitizeIdent (compClassName cls)
        inheritance = case compParentClass cls of
            Just p  -> " : public " ++ sanitizeIdent p
            Nothing -> ""
        directProps = filter (not . compIsInherited) (compProperties cls)
        fields = concatMap emitCppField directProps
        validateImpl = emitCppValidation cls
    in "struct " ++ cName ++ inheritance ++ " {\n" ++
       fields ++
       "\n    virtual ~" ++ cName ++ "() = default;\n\n" ++
       validateImpl ++
       "};\n\n"

emitCppField :: CompiledProperty -> String
emitCppField p =
    let fName = sanitizeIdent (compPropName p)
        pType = compPropType p
        baseType = mapCppType pType
        isCustom = isCustomType pType
        (fType, defaultInit) = case compCardinality p of
            CardZeroOrOne  ->
                if isCustom
                then (baseType, " = nullptr")
                else ("std::optional<" ++ baseType ++ ">", " = std::nullopt")
            CardZeroOrMore -> ("std::vector<" ++ baseType ++ ">", " = {}")
            CardOneOrMore  -> ("std::vector<" ++ baseType ++ ">", " = {}")
            _              ->
                case compDefaultValue p of
                    Just d  -> (baseType, " = " ++ formatCppDefault pType d)
                    Nothing ->
                        if isCustom
                        then (baseType, " = nullptr")
                        else (baseType, "")
    in "    " ++ fType ++ " " ++ fName ++ defaultInit ++ ";\n"

formatCppDefault :: PropertyType -> String -> String
formatCppDefault PTString s = show s
formatCppDefault PTBoolean "true" = "true"
formatCppDefault PTBoolean "True" = "true"
formatCppDefault PTBoolean "false" = "false"
formatCppDefault PTBoolean "False" = "false"
formatCppDefault _ val = val

isCustomType :: PropertyType -> Bool
isCustomType (PTCustom _) = True
isCustomType _            = False

mapCppType :: PropertyType -> String
mapCppType PTInteger    = "int64_t"
mapCppType PTFloat      = "float"
mapCppType PTDouble     = "double"
mapCppType PTString     = "std::string"
mapCppType PTBoolean    = "bool"
mapCppType (PTCustom c) = "std::shared_ptr<" ++ sanitizeIdent c ++ ">"

emitCppValidation :: CompiledClass -> String
emitCppValidation cls =
    let parentCall = case compParentClass cls of
            Just p  -> "        auto parentErrors = " ++ sanitizeIdent p ++ "::validate();\n" ++
                       "        errors.insert(errors.end(), parentErrors.begin(), parentErrors.end());\n"
            Nothing -> ""
        directProps = filter (not . compIsInherited) (compProperties cls)
        propChecks = concatMap emitCppPropChecks directProps
    in "    virtual std::vector<std::string> validate() const {\n" ++
       "        std::vector<std::string> errors;\n" ++
       parentCall ++
       propChecks ++
       "        return errors;\n" ++
       "    }\n"

emitCppPropChecks :: CompiledProperty -> String
emitCppPropChecks p =
    let fName = sanitizeIdent (compPropName p)
        isCustom = isCustomType (compPropType p)
        cardCheck = case compCardinality p of
            CardOneOrMore -> "        if (" ++ fName ++ ".empty()) {\n" ++
                             "            errors.push_back(\"Field '" ++ fName ++ "' must have at least one element\");\n" ++
                             "        }\n"
            CardExactlyOne | isCustom ->
                             "        if (!" ++ fName ++ ") {\n" ++
                             "            errors.push_back(\"Field '" ++ fName ++ "' must not be null\");\n" ++
                             "        }\n"
            _ -> ""
        boundChecks = concatMap (emitCppBoundCheck fName (compPropType p) (compCardinality p)) (compConstraints p)
    in cardCheck ++ boundChecks

emitCppBoundCheck :: String -> PropertyType -> Cardinality -> BoundConstraint -> String
emitCppBoundCheck fName _ card (BoundConstraint op val) =
    let opStr = case op of
            OpGt  -> ">"
            OpGte -> ">="
            OpLt  -> "<"
            OpLte -> "<="
            OpEq  -> "=="
            OpNe  -> "!="
        valStr = valueToString val
        condExpr access = "!(" ++ access ++ " " ++ opStr ++ " " ++ valStr ++ ")"
        errMsg = "Field '" ++ fName ++ "' constraint violated: " ++ show op ++ " " ++ valStr
    in case card of
        CardZeroOrOne ->
            "        if (" ++ fName ++ ".has_value() && " ++ condExpr ("*" ++ fName) ++ ") {\n" ++
            "            errors.push_back(\"" ++ errMsg ++ "\");\n" ++
            "        }\n"
        CardZeroOrMore ->
            "        for (const auto& item : " ++ fName ++ ") {\n" ++
            "            if (" ++ condExpr "item" ++ ") {\n" ++
            "                errors.push_back(\"" ++ errMsg ++ "\");\n" ++
            "                break;\n" ++
            "            }\n" ++
            "        }\n"
        CardOneOrMore ->
            "        for (const auto& item : " ++ fName ++ ") {\n" ++
            "            if (" ++ condExpr "item" ++ ") {\n" ++
            "                errors.push_back(\"" ++ errMsg ++ "\");\n" ++
            "                break;\n" ++
            "            }\n" ++
            "        }\n"
        _ ->
            "        if (" ++ condExpr fName ++ ") {\n" ++
            "            errors.push_back(\"" ++ errMsg ++ "\");\n" ++
            "        }\n"
